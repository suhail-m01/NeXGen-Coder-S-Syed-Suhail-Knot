export function filterLiveSeedHackathons(params: {
  city?: string | null;
  area?: string | null;
  mode?: string;
  price?: string;
  q?: string | null;
  limit?: number;
  page?: number;
}): HackathonListResponse {
  let filtered = [...LIVE_VERIFIED_HACKATHONS];

  if (params.city?.trim()) {
    const searchCity = params.city.trim().toLowerCase();
    const cityMatches = filtered.filter((h) => h.city?.toLowerCase().includes(searchCity));
    // If exact city matches exist, show them; otherwise keep all so user always sees live events
    if (cityMatches.length > 0) {
      filtered = cityMatches;
    }
  }

  if (params.mode && params.mode !== 'all') {
    filtered = filtered.filter((h) => h.mode === params.mode);
  }

  if (params.price && params.price !== 'all') {
    filtered = filtered.filter((h) => (params.price === 'free' ? h.isFree : !h.isFree));
  }

  if (params.q?.trim()) {
    const query = params.q.trim().toLowerCase();
    filtered = filtered.filter(
      (h) =>
        h.title.toLowerCase().includes(query) ||
        (h.description && h.description.toLowerCase().includes(query)) ||
        h.tags.some((t) => t.toLowerCase().includes(query)) ||
        (h.organizer && h.organizer.toLowerCase().includes(query))
    );
  }

  const limit = Math.max(1, params.limit ?? 12);
  const page = Math.max(1, params.page ?? 1);
  const total = filtered.length;
  const paginated = filtered.slice((page - 1) * limit, page * limit);

  return {
    data: paginated,
    meta: {
      page,
      limit,
      total,
      totalPages: Math.ceil(total / limit),
      lastUpdated: new Date().toISOString(),
    },
    facets: {
      locations: Array.from(new Set(LIVE_VERIFIED_HACKATHONS.map((h) => h.city).filter(Boolean))).map((c) => ({
        city: c as string,
        area: null,
      })),
    },
  };
}
